#!/usr/bin/env python3
"""
plugins/vst3native/make_manifests.py — the install manifests of the family.

A family of 48 plug-ins that shares one runtime needs a manifest that says
so.  The old manifest listed every bundle with its files; the new one lists
the bundles, their plug-in, and the runtime they all point at.  Without it
an installer cannot know that the interpreter has to be installed once, and
a host cannot know where to look for it.

Two documents are written:

``runtime-manifest.json``
    the shared runtime: every file, its size and its hash.

``install-manifest.json``
    the family: every bundle, the plug-in inside it, its size and its
    hash, and the runtime directory the bundle refers to.

Both carry a "do not edit" line, because they are generated.

The command line is ``scripts/vst3_runtime.py manifest``.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Sequence

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import stage_runtime  # noqa: E402  (the module lives next to this one)


def write_runtime_manifest(runtime_dir: Path, out_path: Path | None = None) -> Path:
    """Write the manifest of the runtime directory."""
    return stage_runtime.write_runtime_manifest(runtime_dir, out_path)


def write_family_manifest(roots: Sequence[Path], runtime_dir: Path | None = None,
                           out_path: Path | None = None) -> Path:
    """Write the manifest of the family.

    Every bundle is listed with the plug-in it holds, the size of the
    bundle and the hash of the plug-in.  The runtime is listed once, with
    the directory it lives in, because that is what the plug-in loads.
    """
    bundles: list[Path] = []
    for root in roots:
        bundles.extend(stage_runtime.find_bundles(root))

    runtime = None
    if runtime_dir is not None:
        runtime = Path(runtime_dir)
    elif bundles:
        runtime = stage_runtime.discover_runtime(bundles[0])

    entries = []
    total = 0
    root = stage_runtime.family_root(roots)

    for bundle in bundles:
        plug_in = stage_runtime.bundle_binary(bundle)
        size = stage_runtime.bundle_size(bundle)
        total += size

        try:
            where = bundle.relative_to(root).as_posix()
        except ValueError:
            where = bundle.as_posix()

        entry = {
            "name": bundle.name,
            "path": where,
            "bytes": size,
            "plug_in": plug_in.name if plug_in is not None else None,
            "plug_in_bytes": plug_in.stat().st_size if plug_in is not None else 0,
            "plug_in_sha256": (stage_runtime.file_hash(plug_in)
                               if plug_in is not None else None),
            "carries_runtime": bool(stage_runtime.runtime_members(bundle)),
        }

        if runtime is not None:
            entry["runtime"] = runtime.name

        entries.append(entry)

    document = {
        "do not edit": "generated by plugins/vst3native/make_manifests.py",
        "kind": "auralis.vst3.family",
        "version": 1,
        "bundles": len(entries),
        "total_bytes": total,
        "runtime": runtime.name if runtime is not None else None,
        "runtime_shared": runtime is not None,
        "entries": entries,
    }

    target = Path(out_path) if out_path is not None else (
        stage_runtime.family_root(roots) / stage_runtime.FAMILY_MANIFEST_NAME)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")

    return target


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Write the manifests of the VST3 family")
    parser.add_argument("roots", nargs="+", help="the directories that hold the bundles")
    parser.add_argument("--runtime", default=None, help="the shared runtime directory")
    parser.add_argument("--out", default=None, help="where the family manifest is written")

    args = parser.parse_args(argv)
    roots = [Path(root) for root in args.roots]
    runtime = Path(args.runtime) if args.runtime else None

    written = []

    if runtime is not None and runtime.is_dir():
        written.append(write_runtime_manifest(runtime))

    written.append(write_family_manifest(roots, runtime, Path(args.out) if args.out else None))

    for path in written:
        print(path)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
