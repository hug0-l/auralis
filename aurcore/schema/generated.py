def param_index(code: str, name: str) -> int:
    """Return the id of a parameter (its index inside its module)."""
    try:
        return PARAM_ID[code][name]
    except KeyError:
        raise KeyError(f"unknown parameter {name!r} for module {code!r}") from None


def param_name(code: str, index: int) -> str:
    """Return the parameter name at an id inside a module."""
    try:
        return CODE_BY_INDEX[code][index]
    except KeyError:
        raise KeyError(f"unknown parameter index {index} for module {code!r}") from None


