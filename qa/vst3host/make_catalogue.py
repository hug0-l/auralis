#!/usr/bin/env python3
"""
qa/vst3host/make_catalogue.py - write the catalogue the host reads.

The host measures how long a plug-in delays its output.  The range it
searches is not a constant in the host: it is the largest delay the
product's modules declare, plus a margin, so that the host can measure
every delay the product is able to produce.  The host is a C++ program and
the catalogue is Python, so the catalogue is written to a file the host
reads - one line per module, with the delay the module declares and the
tolerance of that delay.

The tolerance rules are the ones the survey uses (qa/survey/survey.py,
``latency_tolerance``):

  * a module that declares a delay must delay the signal by exactly that
    delay - the tolerance is 2 samples (41.7 us at 48 kHz), because the
    delay line of a module has a fixed length and the measurement resolves
    it to the sample,
  * a module that declares no delay may not delay the signal by more than
    a block - the tolerance is 64 samples (1.33 ms at 48 kHz), because the
    cross correlation of a filtered signal peaks at the group delay of the
    filter and not at a latency,
  * a module whose delay is not a constant - a module that warps the time
    axis - carries the tolerance it needs in its own specification
    (qa/survey/specs.py).

usage:
    python qa/vst3host/make_catalogue.py [--out FILE] [--check]

    --out FILE   where the catalogue is written
                (default: qa/vst3host/catalogue.tsv)
    --check      do not write anything; say whether the file on disk is the
                one this script would write
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

#: The sample rate the modules are created at.  It is the rate the host
#: runs at, so that the delays are the delays of the same modules.
SAMPLE_RATE = 48_000

#: The channel count the modules are created at.
CHANNELS = 2

#: Where the catalogue is written.
DEFAULT_OUT = HERE / "catalogue.tsv"

#: The header of the file.  The fields are separated by a tab.
HEADER = (
    "# The catalogue of the Auralis modules, as the host needs it.\n"
    "#\n"
    "# One line per module, the fields separated by a tab:\n"
    "#\n"
    "#   code, class id, display name, declared latency, latency tolerance\n"
    "#\n"
    "# The declared latency is the delay the module puts into the signal, in\n"
    "# samples of the module's own output at 48 kHz.  The tolerance is how far\n"
    "# the measured delay may be from the declared one, in samples.\n"
    "#\n"
    "# Generated by qa/vst3host/make_catalogue.py.  Do not edit by hand.\n"
)


class _Declared:
    """The one thing the tolerance rule of the survey wants to know."""

    def __init__(self, declared: int) -> None:
        self.latency_declared = int(declared)


def module_rows() -> list[tuple[str, str, str, int, int]]:
    """Return one row per module of the catalogue.

    Every row is the code of the module, the class identifier the plug-in
    of that module carries, the name the module is shown under, the delay
    the module declares and the tolerance of that delay.
    """
    from aurcore import registry
    import aurcore.modules  # noqa: F401 - importing registers the modules
    from plugins import identity
    from qa.survey import specs
    from qa.survey import survey

    rows: list[tuple[str, str, str, int, int]] = []

    for info in registry.all():
        module = registry.create(info.code, SAMPLE_RATE, CHANNELS)
        declared = int(getattr(module, "latency_samples", 0) or 0)
        spec = specs.spec_for(info.code)
        tolerance = int(survey.latency_tolerance(spec, _Declared(declared)))
        record = identity.identity_for(info.code)

        rows.append(
            (
                info.code,
                str(record.vst3_fuid).lower(),
                info.display_name,
                declared,
                tolerance,
            )
        )

    return rows


def render(rows: list[tuple[str, str, str, int, int]]) -> str:
    """Return the text of the catalogue file."""
    lines = [HEADER]
    for code, class_id, display_name, declared, tolerance in rows:
        name = display_name.replace("\t", " ").replace("\n", " ")
        lines.append(f"{code}\t{class_id}\t{name}\t{declared}\t{tolerance}\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="where the catalogue is written")
    parser.add_argument("--check", action="store_true",
                        help="only say whether the file on disk is up to date")
    args = parser.parse_args(argv)

    rows = module_rows()
    text = render(rows)
    target = Path(args.out)

    if args.check:
        on_disk = target.read_text(encoding="utf-8") if target.is_file() else ""
        if on_disk == text:
            print(f"{target} is up to date ({len(rows)} module(s))")
            return 0
        print(f"{target} is out of date: {len(rows)} module(s) would be written")
        return 1

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")

    largest = max((row[3] for row in rows), default=0)
    print(f"{target}: {len(rows)} module(s), the largest declared delay is {largest} samples")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
